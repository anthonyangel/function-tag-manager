// Package filters determines whether resources support tags
package filters

// ResourceFilter maps a resource's GroupKind to the name of the
// spec.forProvider field that holds its tags. Resources that don't support
// tags are not present.
type ResourceFilter map[string]string

// ProviderFilter indicates which of a provider's resources support tags,
// and the name of the spec.forProvider field that holds them.
type ProviderFilter struct {
	// Field is the name of the spec.forProvider field that holds tags.
	Field string
	// Resources maps a GroupKind to whether it supports Field.
	Resources map[string]bool
	// Rules are the limits the provider places on tags. They are optional.
	Rules *Rules
}

// NewProviderFilter returns a ProviderFilter for the given field.
func NewProviderFilter(field string, resources map[string]bool) ProviderFilter {
	return ProviderFilter{Field: field, Resources: resources}
}

// WithRules returns a copy of the ProviderFilter that has the given Rules.
func (p ProviderFilter) WithRules(rules Rules) ProviderFilter {
	p.Rules = &rules
	return p
}

// allProviders returns the filters for all of the supported providers.
func allProviders() []ProviderFilter {
	return []ProviderFilter{
		NewAWSResourceFilter(),
		NewAzureResourceFilter(),
		// The rules are set here, and not in the generated filter, so
		// regenerating the filter doesn't remove them.
		NewGCPResourceFilter().WithRules(GCPLabelRules()),
	}
}

// NewResourceFilter returns a map of resources that support tags.
// these values were generated by querying Provider CRDs for `spec.forProvider.tags`
// support (`spec.forProvider.labels` for GCP).
func NewResourceFilter() ResourceFilter {
	return newResourceFilter(allProviders()...)
}

// newResourceFilter merges the resources that support tags in each provider.
func newResourceFilter(providers ...ProviderFilter) ResourceFilter {
	all := make(ResourceFilter)

	for _, pf := range providers {
		for groupKind, supported := range pf.Resources {
			if supported {
				all[groupKind] = pf.Field
			}
		}
	}

	return all
}

// NewResourceRules returns the rules for the tags of resources that support
// tags. Resources whose provider has no rules are not present.
func NewResourceRules() ResourceRules {
	return newResourceRules(allProviders()...)
}

// newResourceRules merges the rules for the resources that support tags in each
// provider.
func newResourceRules(providers ...ProviderFilter) ResourceRules {
	all := make(ResourceRules)

	for _, pf := range providers {
		if pf.Rules == nil {
			continue
		}

		for groupKind, supported := range pf.Resources {
			if supported {
				all[groupKind] = *pf.Rules
			}
		}
	}

	return all
}
